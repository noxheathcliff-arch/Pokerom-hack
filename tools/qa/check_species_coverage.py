#!/usr/bin/env python3
"""Species coverage checker for Pokemon Confluence (brief D, ENCOUNTERS_PLAN.md section 11).

Proves (or disproves) that every national species 1..1025 is obtainable, per ending.

Sources of "obtainable" (Emerald build only; FRLG data and *_Frlg maps are ignored):
  1. src/data/wild_encounters.json  (gWildMonHeaders, labels starting with "g", unused/Altering Cave skipped)
  2. scripts: givemon / setwildbattle / giveegg / createmon with a literal SPECIES_* in data/maps/*/scripts.inc
     and data/scripts/*.inc
  3. in-game trades: src/data/trade.h (.species = what the player receives)
  4. --plan CSV (docs/hack/data/species_channels.csv): planned channels not yet in code
     columns: species,channel,map,method,chapter,endings,status,note   (endings = ALL or F1|F2|...)
Closure: forward evolutions (blocked: IF_REGION <> HOENN, trade-partner evolutions unless both
partners obtainable, EVO_NONE) + breeding back to the egg species (skipped for NO_EGGS_DISCOVERED).

Usage:
  python3 tools/qa/check_species_coverage.py                 # implemented data only
  python3 tools/qa/check_species_coverage.py --plan docs/hack/data/species_channels.csv
  ... --strict  (exit 1 if any ending < 1025)   ... --missing (print missing species)
"""
import argparse, csv, glob, json, os, re, sys, collections

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
ENDINGS = ['F1', 'F2', 'F3', 'F4', 'F5']
# Species whose data is generated by macros (forms) and must be linked by hand.
MANUAL_EDGES = [('SCATTERBUG', 'SPEWPA'), ('SPEWPA', 'VIVILLON'), ('FLABEBE', 'FLOETTE'),
                ('FLOETTE', 'FLORGES'), ('MILCERY', 'ALCREMIE')]


def read(p):
    with open(os.path.join(ROOT, p), encoding='utf-8') as f:
        return f.read()


def national_dex():
    txt = read('include/constants/pokedex.h')
    names = [x for x in re.findall(r'^\s*NATIONAL_DEX_(\w+),', txt, re.M) if x != 'NONE']
    return names[:1025]


def parse_species():
    src = ''.join(read(os.path.relpath(f, ROOT)) for f in
                  sorted(glob.glob(os.path.join(ROOT, 'src/data/pokemon/species_info/gen_*_families.h'))))
    parts = re.split(r'\n\s*\[(SPECIES_\w+)\]\s*=\s*\n', src)
    info = {}
    edge_re = re.compile(r'\{(EVO_\w+)\s*,\s*([^,{}]+?)\s*,\s*(SPECIES_\w+)\s*(?:,\s*CONDITIONS\(((?:\s*\{[^}]*\}\s*,?)*)\))?\s*\}')
    for i in range(1, len(parts), 2):
        key, body = parts[i], parts[i + 1]
        m = re.search(r'\.evolutions\s*=\s*EVOLUTION\((.*?)\)\s*,\s*\n', body, re.S)
        evos = [(e.group(1), e.group(2), e.group(3), e.group(4) or '') for e in edge_re.finditer(m.group(1))] if m else []
        eggs = re.search(r'\.eggGroups\s*=\s*MON_EGG_GROUPS\(([^)]*)\)', body)
        info[key[8:]] = dict(evos=evos, noeggs=bool(eggs and 'NO_EGGS_DISCOVERED' in eggs.group(1)))
    return info


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--plan')
    ap.add_argument('--strict', action='store_true')
    ap.add_argument('--missing', action='store_true')
    a = ap.parse_args()

    dex = national_dex()
    natset = set(dex)
    by_len = sorted(dex, key=len, reverse=True)
    info = parse_species()

    def base(s):
        s = s[8:] if s.startswith('SPECIES_') else s
        if s in natset:
            return s
        for n in by_len:
            if s.startswith(n + '_'):
                return n
        return None

    # key-level graph (forms kept distinct: Meowth-Galar -> Perrserker)
    succ, pred, blocked = collections.defaultdict(set), collections.defaultdict(set), []
    for k, v in info.items():
        for meth, param, tgt, cond in v['evos']:
            t = tgt[8:]
            if meth == 'EVO_NONE':
                continue
            if 'IF_REGION' in cond and 'IF_NOT_REGION' not in cond and 'REGION_HOENN' not in cond:
                blocked.append((k, t, 'region'))
                continue
            if 'IF_TRADE_PARTNER_SPECIES' in cond:
                partner = re.search(r'SPECIES_(\w+)', cond).group(1)
                succ[k].add((t, partner))
            else:
                succ[k].add((t, None))
            pred[t].add(k)
    for x, y in MANUAL_EDGES:
        succ[x].add((y, None)); pred[y].add(x)

    def egg_root(k):
        seen = set()
        while pred.get(k) and k not in seen:
            seen.add(k)
            k = sorted(pred[k])[0]
        return k

    def closure(start):
        have = set(start)
        changed = True
        while changed:
            changed = False
            for k in list(have):
                for t, partner in succ.get(k, ()):
                    if t in have:
                        continue
                    if partner and partner not in have:
                        continue
                    have.add(t); changed = True
                r = egg_root(k)
                if r not in have and not info.get(k, {}).get('noeggs', False):
                    have.add(r); changed = True
        return have

    # 1. wild
    sources = collections.defaultdict(set)  # ending -> species keys
    wild = json.loads(read('src/data/wild_encounters.json'))['wild_encounter_groups'][0]['encounters']
    impl = set()
    for e in wild:
        lbl = e['base_label']
        if not lbl.startswith('g') or 'Unused' in lbl or 'AlteringCave' in lbl:
            continue
        for kind in ('land_mons', 'water_mons', 'rock_smash_mons', 'fishing_mons', 'hidden_mons'):
            for mon in e.get(kind, {}).get('mons', []):
                impl.add(mon['species'][8:])
    # 2. scripts
    files = [f for f in glob.glob(os.path.join(ROOT, 'data/maps/*/scripts.inc')) if not os.path.dirname(f).endswith('_Frlg')]
    files += glob.glob(os.path.join(ROOT, 'data/scripts/*.inc'))
    for f in files:
        with open(f, encoding='utf-8', errors='ignore') as fh:
            for m in re.finditer(r'^\s*(?:givemon|setwildbattle|giveegg|createmon)\s+(?:\w+\s*,\s*)?SPECIES_(\w+)', fh.read(), re.M):
                impl.add(m.group(1))
    # 3. trades
    for m in re.finditer(r'\.species\s*=\s*SPECIES_(\w+)', read('src/data/trade.h')):
        impl.add(m.group(1))
    for en in ENDINGS:
        sources[en] |= impl
    # 4. plan
    planned = collections.Counter()
    if a.plan:
        with open(a.plan, encoding='utf-8') as fh:
            for row in csv.DictReader(fh):
                sp = row['species'].strip().replace('SPECIES_', '')
                ends = ENDINGS if row.get('endings', 'ALL').strip() in ('', 'ALL') else row['endings'].split('|')
                for en in ends:
                    sources[en.strip()].add(sp)
                planned[row.get('channel', '?')] += 1

    ok = True
    print(f'national species: {len(dex)} | implemented direct sources: {len(impl)} species keys')
    if planned:
        print('planned rows by channel: ' + ', '.join(f'{k}={v}' for k, v in sorted(planned.items())))
    for en in ENDINGS:
        have = {base(k) for k in closure(sources[en])} - {None}
        miss = [n for n in dex if n not in have]
        print(f'{en}: {len(dex) - len(miss)}/{len(dex)} obtainable' + (f' | missing {len(miss)}' if miss else ''))
        if miss:
            ok = False
            if a.missing:
                print('  ' + ' '.join(miss))
    if blocked:
        print('region-blocked evolutions (need a direct channel): ' + ', '.join(sorted({t for _, t, _ in blocked})))
    if a.strict and not ok:
        sys.exit(1)


if __name__ == '__main__':
    main()
